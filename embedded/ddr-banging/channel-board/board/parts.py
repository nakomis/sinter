# fetched-name -> our-name, per key. Only EasyEDA's active-low "~{xOE}" spelling
# differs from the names the rest of the code uses; the RP2354B symbol already
# uses IOVDD, DVDD, VREG_*, USB_DP/DM, XIN/XOUT, SWCLK/SWDIO, RUN and QSPI_SS
# (pin 75) directly. Only the ADC-capable GPIO40..47 carry a "_ADCn" suffix.
ALIASES = {
    "RP2354B": {f"GPIO{40 + n}_ADC{n}": f"GPIO{40 + n}" for n in range(8)},
    "XLAT": {"~{1OE}": "1OE#", "~{2OE}": "2OE#"},
}


def _load(key, row):
    value, lcsc, fp_stem, sym, extended, rot = row
    fp = load_footprint(LCSC_FP / f"{fp_stem}.kicad_mod")
    pins = {}
    if sym is None:     # footprint-only part: one passive pin per numbered pad, name = number
        pins = {p.number: [p.number] for p in fp.pads if p.number}
        pin_types = {n: "passive" for n in pins}
    else:
        alias = ALIASES.get(key, {})
        for name, nums in load_symbol_pins(LCSC_SYM, sym).items():
            pins.setdefault(alias.get(name, name), []).extend(nums)
        pin_types = load_symbol_pin_types(LCSC_SYM, sym)
    # Through-hole only if most numbered signal pads are drilled; unnumbered thermal
    # pads and mounting pegs (WSON EP, USB-C shell) do not make a part THT.
    numbered = [p for p in fp.pads if p.number]
    tht = bool(numbered) and sum(p.kind == "thru_hole" for p in numbered) * 2 > len(numbered)
    return PartDef(key, value, lcsc, fp, pins, pin_types, extended, tht, rot)


# Extended parts whose CPL rotation offset has been checked. EasyEDA-fetched footprints follow
# JLCPCB's own orientation convention, so their offset is 0. The generated DIMM footprint is
# hand-soldered-style through-hole whose orientation is fixed by its key slot, so also 0.
# The final check is a look at JLCPCB's placement preview at order time.
ROTATION_CHECKED = {k for k, row in _TABLE.items() if row[4] and row[5] == 0}

PARTS = {k: _load(k, row) for k, row in _TABLE.items()}


def part(key):
    return PARTS[key]
